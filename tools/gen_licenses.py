#!/usr/bin/env python3
"""Collect license texts of third-party code that ships inside PageWeave.

- UI: production npm dependencies bundled into the frontend (type-only packages excluded).
- Rust: crates compiled into the binaries, via `cargo about` (template tools/about.hbs).

Writes third_party/licenses/ui-npm.txt and third_party/licenses/rust-crates.txt. With --check,
exits 1 if the committed files are out of date (CI uses this). Fails if a package has no license
text, so a missing notice cannot slip into a release unnoticed.

Usage: python3 -I tools/gen_licenses.py [--check] [--skip-rust]
"""
from __future__ import annotations

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "third_party" / "licenses"
TYPE_ONLY = {"@types/react", "@types/react-dom", "csstype"}
LICENSE_NAMES = ("LICENSE", "LICENSE.md", "LICENSE.txt", "LICENCE", "license", "license.md", "LICENSE-MIT", "LICENSE_MIT")
# npm packages published without a license file whose same-version Rust crate (same project, same
# license) carries the text. Used only as an explicit, per-package fallback.
CRATE_FALLBACK = {"@tauri-apps/plugin-dialog": "tauri-plugin-dialog", "@tauri-apps/plugin-opener": "tauri-plugin-opener"}


def crate_license(crate: str, version: str) -> str | None:
    registry = Path.home() / ".cargo" / "registry" / "src"
    for d in registry.glob(f"*/{crate}-{version}"):
        for n in LICENSE_NAMES + ("LICENSE-APACHE", "LICENSE_APACHE-2.0"):
            if (d / n).is_file():
                return (d / n).read_text(encoding="utf-8", errors="replace")
    return None


def npm_packages() -> list[tuple[str, str, Path]]:
    app = ROOT / "app"
    raw = subprocess.run(["npm", "ls", "--omit=dev", "--all", "--json", "--long"], cwd=app,
                         capture_output=True, text=True, check=False).stdout
    tree = json.loads(raw)
    found: dict[str, tuple[str, Path]] = {}

    def walk(node: dict) -> None:
        for name, dep in (node.get("dependencies") or {}).items():
            if name in TYPE_ONLY:
                continue
            path = Path(dep.get("path") or app / "node_modules" / name)
            found[name] = (dep.get("version", "?"), path)
            walk(dep)

    walk(tree)
    return sorted((n, v, p) for n, (v, p) in found.items())


def npm_text() -> str:
    parts = ["Third-party UI packages bundled into PageWeave (generated by tools/gen_licenses.py).", ""]
    for name, version, path in npm_packages():
        meta = json.loads((path / "package.json").read_text(encoding="utf-8"))
        lic = meta.get("license") or meta.get("licenses")
        text = next((p.read_text(encoding="utf-8", errors="replace") for n in LICENSE_NAMES if (p := path / n).is_file()), None)
        if text is None and name in CRATE_FALLBACK:
            text = crate_license(CRATE_FALLBACK[name], version)
            if text is not None:
                text = f"(License text taken from the same-version Rust crate {CRATE_FALLBACK[name]} {version}.)\n\n{text}"
        if text is None:
            raise SystemExit(f"error: {name}@{version} ships no license file")
        parts += ["=" * 78, f"{name} {version} — {lic}", "=" * 78, text.strip(), ""]
    return "\n".join(parts) + "\n"


def rust_text() -> str:
    r = subprocess.run(["cargo", "about", "generate", "--locked", "--fail", str(ROOT / "tools" / "about.hbs")],
                       cwd=ROOT, capture_output=True, text=True, check=False)
    if r.returncode != 0:
        raise SystemExit(f"error: cargo about failed:\n{r.stderr[-2000:]}")
    return r.stdout


def main() -> int:
    check = "--check" in sys.argv
    outputs = {OUT / "ui-npm.txt": npm_text()}
    if "--skip-rust" not in sys.argv:
        outputs[OUT / "rust-crates.txt"] = rust_text()
    stale = []
    for path, text in outputs.items():
        if check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)} ({len(text)} bytes)")
    if stale:
        print("out of date (run tools/gen_licenses.py): " + ", ".join(map(str, stale)), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
