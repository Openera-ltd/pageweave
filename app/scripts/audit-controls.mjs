// Static interaction audit (PRD 13 "Interaction audit"). Fails if:
//  - a <button> or role="menuitem"/"tab"/"radio"/"option" element in src/ has no click handler;
//  - an icon-only <button> (no text child) has no aria-label;
//  - a data-command value is not a registered command;
//  - a registered command has no E2E or unit-test reference (reported as NOT COVERED; fails with --strict).
// Also writes docs/INTERACTION_INVENTORY.md listing every command, its shortcut and test coverage.

import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const repo = join(root, "..");
const strict = process.argv.includes("--strict");

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => (e.isDirectory() ? walk(join(dir, e.name)) : [join(dir, e.name)]));
}

const sources = walk(join(root, "src")).filter((f) => f.endsWith(".tsx") && !f.endsWith(".test.tsx"));
const registry = readFileSync(join(root, "src/commands.ts"), "utf8");
const commandIds = [...registry.matchAll(/\{ id: "([a-zA-Z.]+)", label: "([^"]+)"[^}]*shortcuts: \[([^\]]*)\]/g)].map((m) => ({
  id: m[1],
  label: m[2],
  shortcuts: m[3].split(",").map((s) => s.trim().replace(/"/g, "")).filter(Boolean),
}));
const known = new Set(commandIds.map((c) => c.id));

const problems = [];

/** Extract JSX opening tags (handles nested braces and `=>` inside attributes). */
function openingTags(src, tagName) {
  const out = [];
  let i = 0;
  while ((i = src.indexOf(`<${tagName}`, i)) !== -1) {
    const after = src[i + tagName.length + 1];
    if (after && /[A-Za-z0-9]/.test(after)) {
      i++;
      continue;
    }
    let depth = 0;
    let j = i + 1;
    for (; j < src.length; j++) {
      const ch = src[j];
      if (ch === "{") depth++;
      else if (ch === "}") depth--;
      else if (ch === ">" && depth === 0 && src[j - 1] !== "=") break;
    }
    const tag = src.slice(i, j + 1);
    const selfClosing = tag.endsWith("/>");
    const close = selfClosing ? -1 : src.indexOf(`</${tagName}>`, j);
    out.push({ tag, body: close > 0 ? src.slice(j + 1, close) : "", line: src.slice(0, i).split("\n").length });
    i = j;
  }
  return out;
}

for (const file of sources) {
  const src = readFileSync(file, "utf8");
  const rel = relative(repo, file);
  for (const { tag, body, line } of openingTags(src, "button")) {
    if (!/onClick=|type="submit"/.test(tag)) problems.push(`${rel}:${line} <button> without onClick`);
    const hasText = body.replace(/<[^>]+>/g, "").replace(/\{[^}]*\}/g, "x").trim().length > 0;
    if (!hasText && !/aria-label=/.test(tag)) problems.push(`${rel}:${line} icon-only <button> without aria-label`);
  }
  for (const m of src.matchAll(/data-command="([^"]+)"/g)) {
    if (!known.has(m[1])) problems.push(`${rel}: data-command="${m[1]}" is not a registered command`);
  }
  // Any JSX element given an interactive role must handle clicks itself.
  for (const tagName of ["div", "li", "span", "button"]) {
    for (const { tag, line } of openingTags(src, tagName)) {
      const role = /\srole="(menuitem|tab|radio|option|checkbox|switch)"/.exec(tag);
      if (role && !/onClick=/.test(tag)) problems.push(`${rel}:${line} role="${role[1]}" without onClick`);
    }
  }
}

// Coverage: a command counts as covered when a test triggers it by ID, data-command or its shortcut.
const e2e = readFileSync(join(root, "e2e/run.mjs"), "utf8");
const unit = walk(join(root, "src")).filter((f) => f.endsWith(".test.ts") || f.endsWith(".test.tsx")).map((f) => readFileSync(f, "utf8")).join("\n");
const keysOf = (sc) => sc.split("+").map((k) => (k === "Ctrl" ? "Control" : k));
const covered = (c) => {
  if (e2e.includes(`"${c.id}"`) || e2e.includes(`data-command="${c.id}"`) || unit.includes(`"${c.id}"`)) return true;
  return c.shortcuts.some((sc) => {
    const ks = keysOf(sc);
    const last = ks[ks.length - 1];
    const lit = ks.slice(0, -1).map((k) => `"${k}"`).join(", ");
    const keyForms = [`"${last}"`, `"${last.toLowerCase()}"`];
    return keyForms.some((k) => e2e.includes(`s.keys([${lit}${lit ? ", " : ""}${k}])`));
  });
};

const rows = commandIds.map((c) => ({ ...c, covered: covered(c) }));
const notCovered = rows.filter((r) => !r.covered);

const md = [
  "# Interaction Inventory (generated)",
  "",
  "Generated by `app/scripts/audit-controls.mjs` from `app/src/commands.ts` and the test suites. Do not edit by hand.",
  "Every toolbar button, menu item, context-menu entry and shortcut dispatches one of these command IDs; each command",
  "declares availability with a user-facing reason when disabled (see `CommandHandlers` in `app/src/App.tsx`).",
  "",
  "| Command ID | Label | Default shortcut(s) | Test coverage |",
  "|---|---|---|---|",
  ...rows.map((r) => `| \`${r.id}\` | ${r.label} | ${r.shortcuts.join(", ") || "—"} | ${r.covered ? "Exercised by tests" : "**NOT COVERED**"} |`),
  "",
  `Coverage: ${rows.length - notCovered.length} of ${rows.length} commands exercised by unit or real-app E2E tests.`,
  "",
].join("\n");
writeFileSync(join(repo, "docs/INTERACTION_INVENTORY.md"), md);

console.log(`commands: ${rows.length}, covered: ${rows.length - notCovered.length}`);
if (notCovered.length) console.log(`NOT COVERED: ${notCovered.map((r) => r.id).join(", ")}`);
if (problems.length) {
  console.error(problems.map((p) => `PROBLEM ${p}`).join("\n"));
}
process.exit(problems.length || (strict && notCovered.length) ? 1 : 0);
